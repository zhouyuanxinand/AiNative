/** Actual preparation/pull components with isolated display data; no business commands. */
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:18370';
const output = process.env.SCREENSHOT_DIR;
if (output) await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 950 } });
const errors = [], writes = [], measurements = [];
page.on('pageerror', error => errors.push(error.message));
page.on('request', request => { if (!['GET', 'HEAD', 'OPTIONS'].includes(request.method())) writes.push(request.method()); });
await page.route('**/__taskbook-layout-fixture', route => route.fulfill({ contentType: 'text/html', body: '<html lang="zh-CN"><head><meta name="viewport" content="width=device-width, initial-scale=1"><title>任务书布局复核夹具</title></head><body><div id="fixture"></div></body></html>' }));
const snap = async name => { if (output) await page.screenshot({ path: join(output, name) }); };
try {
  await page.goto(`${base}/__taskbook-layout-fixture`);
  await page.evaluate(async () => {
    const refresh = await import('/@react-refresh');
    refresh.default.injectIntoGlobalHook(window);
    window.$RefreshReg$ = () => {};
    window.$RefreshSig$ = () => type => type;
    window.__vite_plugin_react_preamble_installed__ = true;
    const React = (await import('/node_modules/.vite/deps/react.js')).default;
    const { createRoot } = (await import('/node_modules/.vite/deps/react-dom_client.js')).default;
    const { PlatformTheme } = await import('/src/components/ui/PlatformTheme.tsx');
    const { TaskbookPreparation } = await import('/src/features/rd/TaskbookPreparation.tsx');
    const { WorkpackagePanel } = await import('/src/features/rd/WorkpackagePanel.tsx');
    for (const file of ['/src/styles.css', '/src/features/rd/rd.css', '/src/features/rd/caseWorkspace.css', '/src/features/rd/rdExperience.css', '/src/features/rd/caseOutcome.css', '/src/features/rd/rdApplicationShell.css']) await import(file);
    const researchCase = { id: 'layout-case', stage: 'planning', status: 'active', input_revision: 1, requirements: [], sources: [], workpackages: [], business_lifecycle: { policy_version: 'v2' }, product_route: { value: 'modification' }, composition_route: { value: 'direct' }, taskbook_binding: { id: 'layout-binding', status: 'current', input_revision: 1, adopted_at: '2026-11-02T00:00:00Z', workflow: { title: '改型研发流程（布局测试数据）', version: 1 }, scope: '根据需求和产品规范编制任务书，保留原文依据。', rationale: '本地布局夹具，仅验证真实组件的边界和间距。', document_template: { title: '液冷管路研制任务书' }, fingerprint: 'a'.repeat(64) } };
    const catalog = { workpackage_definitions: [{ id: 'taskbook', version: '2', title: '任务书装配与校验', allowed_stages: ['planning'] }], research_workflow_templates: [] };
    const common = { researchCase, catalog, busy: false, command: async () => { throw new Error('Display fixture must not execute commands'); }, onDirtyChange: () => {} };
    createRoot(document.getElementById('fixture')).render(React.createElement(PlatformTheme, null, React.createElement('div', { className: 'rd-shell rd-application-shell', style: { display: 'block' } }, React.createElement('main', { className: 'rd-page-content rd-focused-case' }, React.createElement(WorkpackagePanel, { ...common, project: { id: 'layout-project' }, error: '' }), React.createElement(TaskbookPreparation, common)))));
  });
  await page.locator('.rd-pull-workpackage').waitFor();
  await page.locator('.rd-pull-workpackage').scrollIntoViewIfNeeded();
  const select = await page.locator('.rd-pull-workpackage .ant-select-selector').boundingBox();
  const button = await page.getByRole('button', { name: '拉取工作包', exact: true }).boundingBox();
  measurements.push({ select, button });
  await snap('pull-desktop.png');
  assert(Math.abs(select.y - button.y) <= 1 && Math.abs(select.height - button.height) <= 1, 'pull selector and action have aligned top/bottom edges');
  const record = page.locator('article.rd-record-item');
  await record.scrollIntoViewIfNeeded();
  const cardBox = await record.boundingBox(), titleBox = await record.locator('h3').boundingBox();
  measurements.push({ cardBox, titleBox });
  await snap('binding-desktop.png');
  assert(titleBox.x - cardBox.x >= 13 && titleBox.y - cardBox.y >= 13, 'binding record content is inset from its border');
  await page.setViewportSize({ width: 390, height: 520 });
  await page.locator('.rd-pull-workpackage').scrollIntoViewIfNeeded();
  const mobileSelect = await page.locator('.rd-pull-workpackage .ant-select-selector').boundingBox(), mobileButton = await page.getByRole('button', { name: '拉取工作包', exact: true }).boundingBox();
  assert(Math.abs(mobileSelect.width - mobileButton.width) <= 1 && mobileButton.y >= mobileSelect.y + mobileSelect.height, 'mobile pull controls stack without overlap');
  await snap('pull-mobile.png');
  await record.scrollIntoViewIfNeeded();
  assert(await page.locator('.rd-application-shell').evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'long fingerprints do not overflow the page');
  await snap('binding-mobile.png');
  assert.deepEqual(errors, []);
  assert.deepEqual(writes, []);
  if (output) await writeFile(join(output, 'component-layout-receipt.json'), JSON.stringify({ passed: true, componentFixtures: true, measurements, errors, writes }, null, 2));
  console.log(JSON.stringify({ passed: true, componentFixtures: true, measurements, errors, writes }));
} finally { await browser.close(); }
